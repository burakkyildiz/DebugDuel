"""Offline audit of trusted repository fixtures only; never imported by the app."""
import argparse
import collections
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'supabase/questions/catalog.json'
CATALOGS = {'python': CATALOG, 'javascript': ROOT / 'supabase/questions/catalog.javascript.json', 'java': ROOT / 'supabase/questions/catalog.java.json'}
NODE = shutil.which('node')
JAVA = shutil.which('java')
SEED = ROOT / 'supabase/seed.sql'


def render_seed(questions):
    def literal(value):
        return "'" + str(value).replace("'", "''") + "'"
    records = []
    for q in questions:
        fields = [literal(q[key]) for key in (
            'slug', 'version', 'pool', 'language', 'difficulty', 'title', 'prompt',
            'code', 'line_count', 'correct_line', 'explanation', 'corrected_code')]
        fields.append('array[' + ','.join(literal(t) for t in q['tags']) + ']::text[]')
        records.append('  (' + ', '.join(fields) + ')')
    return (
        '-- Generated by python3 scripts/check-questions.py --write-seed.\n'
        '-- Reviewed repository content only. No users, matches or credentials.\n'
        '-- Existing versions are immutable; edit content by adding a new version.\n'
        'insert into private.questions (slug,version,pool,language,difficulty,title,prompt,code,\n'
        '  line_count,correct_line,explanation,corrected_code,tags) values\n'
        + ',\n'.join(records) + '\non conflict (slug,version) do update set\n'
        + ',\n'.join(f'  {key} = excluded.{key}' for key in (
            'pool', 'language', 'difficulty', 'title', 'prompt', 'code', 'line_count',
            'correct_line', 'explanation', 'corrected_code', 'tags')) + ';\n'
    )


def run_java(questions):
    """Compile every Java question and variant in one source file; returns {(slug, variant): pass/fail string}."""
    assert JAVA, 'java (JDK 11+) is required to audit Java questions'
    classes, calls = [], []
    for index, q in enumerate(questions):
        for variant, code in (('o', q['code']), ('f', q['corrected_code'])):
            name = f'Q{index}{variant}'
            checks = ''.join(f'    try {{ {case} r.append(\'1\'); }} catch (Throwable t) {{ r.append(\'0\'); }}\n' for case in q['tests'])
            indented = '\n'.join('  ' + line for line in code.split('\n'))
            classes.append(f'  static class {name} {{\n{indented}\n    static String run() {{\n    StringBuilder r = new StringBuilder();\n{checks}    return r.toString();\n    }}\n  }}')
            calls.append(f'    System.out.println("{index} {variant} " + {name}.run());')
    source = 'import java.util.*;\npublic class Main {\n' + '\n'.join(classes) + '\n  public static void main(String[] args) {\n' + '\n'.join(calls) + '\n  }\n}\n'
    with tempfile.TemporaryDirectory() as directory:
        (Path(directory) / 'Main.java').write_text(source)
        result = subprocess.run([JAVA, '-ea', 'Main.java'], cwd=directory, capture_output=True, text=True, timeout=180)
    assert result.returncode == 0, result.stderr[-3000:]
    outcome = {}
    for line in result.stdout.splitlines():
        index, variant, bits = line.split(' ')
        outcome[(questions[int(index)]['slug'], variant)] = bits
    return outcome


def command(language, code, case):
    if language == 'python':
        return [sys.executable, '-I', '-c', code + '\n' + case]
    assert NODE, 'node is required to audit JavaScript questions'
    prelude = "'use strict'; const assert = require('node:assert');\n"
    return [NODE, '-e', prelude + code + '\n' + case]


def audit(questions):
    assert len(questions) >= 30
    assert {q['language'] for q in questions} <= set(CATALOGS)
    keys = [(q['slug'], q['version']) for q in questions]
    assert len(keys) == len(set(keys)), 'duplicate slug/version'
    assert len({q['code'] for q in questions}) == len(questions), 'duplicate code across pools'
    assert len({q['corrected_code'] for q in questions}) == len(questions), 'duplicate solutions'
    distribution = collections.Counter((q['language'], q['pool'], q['difficulty']) for q in questions)
    languages = {q['language'] for q in questions}
    assert distribution == {(l, p, d): (5 if p == 'duel' else 10) for l in languages for p in ('duel', 'practice') for d in ('easy', 'medium', 'hard')}
    cases = 0
    java_results = run_java([q for q in questions if q['language'] == 'java']) if any(q['language'] == 'java' for q in questions) else {}
    for q in questions:
        label = q['slug']
        for field in ('title', 'prompt', 'explanation'):
            assert q[field].strip(), (label, field)
        assert q['version'] > 0 and q['language'] in CATALOGS
        original, fixed = q['code'], q['corrected_code']
        assert '\r' not in original + fixed and not original.endswith('\n') and not fixed.endswith('\n'), label
        lines, repaired = original.split('\n'), fixed.split('\n')
        assert len(lines) == len(repaired) == q['line_count'], label
        assert 5 <= len(lines) <= 18, label
        assert [i + 1 for i, pair in enumerate(zip(lines, repaired)) if pair[0] != pair[1]] == [q['correct_line']], label
        if q['language'] == 'python':
            compile(original, label, 'exec')
            compile(fixed, label, 'exec')
        assert len(q['tests']) >= 2, label
        # Isolated, bounded child processes execute only checked-in author fixtures.
        # Each test gets fresh globals, so one case cannot contaminate another.
        failures = 0
        if q['language'] == 'java':
            original_bits, fixed_bits = java_results[(label, 'o')], java_results[(label, 'f')]
            assert fixed_bits == '1' * len(q['tests']), (label, 'corrected code fails its tests', fixed_bits)
            assert '0' in original_bits, (label, 'bug is not exposed by tests')
            cases += len(q['tests'])
            continue
        for case in q['tests']:
            for code, expected_pass in ((original, False), (fixed, True)):
                result = subprocess.run(command(q['language'], code, case), capture_output=True, text=True, timeout=5)
                if expected_pass:
                    assert result.returncode == 0, (label, case, result.stderr)
                else:
                    failures += result.returncode != 0
            cases += 1
        assert failures > 0, (label, 'bug is not exposed by tests')
    return cases


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-seed', action='store_true')
    args = parser.parse_args()
    questions = [q for path in CATALOGS.values() for q in json.loads(path.read_text())]
    cases = audit(questions)
    expected = render_seed(questions)
    if args.write_seed:
        SEED.write_text(expected)
    else:
        assert SEED.read_text() == expected, 'Seed drift: run --write-seed and review the diff'
    print(f'{len(questions)} questions / {cases} behavioral cases passed; seed matches catalog.')
