begin;
create extension if not exists pgtap with schema extensions;
set local search_path=public,extensions;
select no_plan();
select ok(not has_function_privilege('anon','public.public_read_admission(text,text)','EXECUTE'),'anonymous clients cannot forge network admission');
select ok(not has_function_privilege('authenticated','public.public_read_admission(text,text)','EXECUTE'),'accounts cannot forge network admission');
select ok(has_function_privilege('service_role','public.public_read_admission(text,text)','EXECUTE'),'server can request admission');
select ok(not has_table_privilege('debug_duel_admission_engine','public.profiles','UPDATE'),'admission cannot update profiles');
select ok(not has_table_privilege('debug_duel_admission_engine','private.rate_limits','DELETE'),'admission cannot delete counters');
select ok(not has_function_privilege('debug_duel_admission_engine','private.verified_actor_id()','EXECUTE'),'admission cannot read protected auth adapter');
select ok(not public.public_read_admission(null,'leaderboard'),'null subject rejected');
select ok(not public.public_read_admission('raw-ip','leaderboard'),'raw subject rejected');
select ok(not public.public_read_admission(repeat('8',64),'arbitrary'),'unknown action rejected');
-- Keep all requests in the same minute even when the suite starts near its end.
select pg_sleep(case when extract(second from clock_timestamp())>58 then 2 else 0 end);
select is((select count(*)::integer from generate_series(1,60) n where public.public_read_admission(repeat('8',64),'leaderboard')),60,'first 60 leaderboard reads accepted');
select ok(not public.public_read_admission(repeat('8',64),'leaderboard'),'61st leaderboard read rejected');
select ok(not public.public_read_admission(repeat('8',64),'leaderboard'),'retry stays rejected');
select is((select max(request_count) from private.rate_limits where subject_hash=repeat('8',64) and action='public_leaderboard'),61,'counter saturates');
select ok(public.public_read_admission(repeat('9',64),'leaderboard'),'separate network has independent quota');
select is((select count(*)::integer from generate_series(1,120) n where public.public_read_admission(repeat('8',64),'health')),120,'health has separate 120/minute quota');
select ok(not public.public_read_admission(repeat('8',64),'health'),'health is bounded');
grant debug_duel_admission_engine to postgres;
grant usage on schema extensions to debug_duel_admission_engine;
set local role debug_duel_admission_engine;
select throws_ok($$insert into private.rate_limits(subject_hash,action,window_start) values(repeat('a',64),'match_create',clock_timestamp())$$,'42501',null,'admission role cannot write game counters');
reset role;
select * from finish();
rollback;
